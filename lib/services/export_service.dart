import '../models/context_thread.dart';
import '../models/group.dart';
import '../theme/app_theme.dart';

class ExportService {
  ExportService._();

  /// Generates a comprehensive, clean GitHub-flavored Markdown document
  /// containing the entire topic summary, attendees, decisions, and action items.
  static String generateMarkdownExport(ContextThread thread, {Group? group}) {
    final buffer = StringBuffer();
    final dateStr = DateFormat('MMMM d, y · h:mm a').format(thread.createdAt);

    buffer.writeln('# 📋 Meeting Summary: ${thread.meetingTitle}');
    buffer.writeln();
    buffer.writeln('- **Date & Time:** $dateStr');
    if (group != null) {
      buffer.writeln('- **Group / Team:** ${group.name}');
    }
    if (thread.participants.isNotEmpty) {
      final attendees = thread.participants.map((p) => p.name).join(', ');
      buffer.writeln('- **Attendees:** $attendees');
    }
    if (thread.vibe != null) {
      buffer.writeln('- **Meeting Vibe:** ${thread.vibe}');
    }
    buffer.writeln();
    buffer.writeln('---');
    buffer.writeln();

    // 1. Executive Summary
    final summaries = thread.blocks.where((b) => b.type == SmartBlockType.summary).toList();
    if (summaries.isNotEmpty) {
      buffer.writeln('## 📝 Executive Summary');
      buffer.writeln();
      for (final s in summaries) {
        buffer.writeln(s.content);
        buffer.writeln();
      }
    }

    // 2. Key Decisions
    final decisions = thread.blocks.where((b) => b.type == SmartBlockType.decision).toList();
    if (decisions.isNotEmpty) {
      buffer.writeln('## 🎯 Key Decisions');
      buffer.writeln();
      for (int i = 0; i < decisions.length; i++) {
        buffer.writeln('${i + 1}. **${decisions[i].content}**');
      }
      buffer.writeln();
    }

    // 3. Action Items Table
    final actionItems = thread.blocks.where((b) => b.type == SmartBlockType.actionItem).toList();
    if (actionItems.isNotEmpty) {
      buffer.writeln('## ✅ Action Items');
      buffer.writeln();
      buffer.writeln('| Status | Task | Assignee | Priority | Due Date |');
      buffer.writeln('| :---: | :--- | :---: | :---: | :---: |');
      for (final item in actionItems) {
        final status = item.isCompleted ? '✓ Done' : '○ Pending';
        final assignee = item.assignee != null ? '@${item.assignee}' : 'Unassigned';
        final priority = item.priority.name.toUpperCase();
        final due = item.dueDate != null ? DateFormat('MMM d, y').format(item.dueDate!) : '-';
        buffer.writeln('| $status | ${item.content.replaceAll('|', '/')} | $assignee | $priority | $due |');
      }
      buffer.writeln();
    }

    // 4. Key Insights
    final insights = thread.blocks.where((b) => b.type == SmartBlockType.keyInsight).toList();
    if (insights.isNotEmpty) {
      buffer.writeln('## 💡 Key Insights & Notes');
      buffer.writeln();
      for (final insight in insights) {
        buffer.writeln('- ${insight.content}');
      }
      buffer.writeln();
    }

    if (thread.recordingUrl != null) {
      buffer.writeln('---');
      buffer.writeln();
      buffer.writeln('🎙️ **Recording Reference:** [Listen / Download Cloud Audio](${thread.recordingUrl})');
      buffer.writeln();
    }

    buffer.writeln('---');
    buffer.writeln('*Generated by Convene AI on ${DateFormat.yMMMd().format(DateTime.now())}*');

    return buffer.toString();
  }

  /// Builds a `mailto:` link with a pre-formatted email digest of the meeting outcomes.
  static String generateEmailDigestUrl(ContextThread thread, {Group? group}) {
    final subject = 'Meeting Summary: ${thread.meetingTitle}';
    final dateStr = DateFormat('MMM d, y').format(thread.createdAt);

    final buffer = StringBuffer();
    buffer.writeln('Hi team,');
    buffer.writeln();
    buffer.writeln('Here is the summary and action item digest from our meeting "$thread.meetingTitle" ($dateStr):');
    buffer.writeln();

    // Decisions
    final decisions = thread.blocks.where((b) => b.type == SmartBlockType.decision).toList();
    if (decisions.isNotEmpty) {
      buffer.writeln('KEY DECISIONS:');
      for (int i = 0; i < decisions.length; i++) {
        buffer.writeln('• ${decisions[i].content}');
      }
      buffer.writeln();
    }

    // Action Items
    final actionItems = thread.blocks.where((b) => b.type == SmartBlockType.actionItem).toList();
    if (actionItems.isNotEmpty) {
      buffer.writeln('ACTION ITEMS:');
      for (final item in actionItems) {
        final status = item.isCompleted ? '[DONE]' : '[TODO]';
        final assignee = item.assignee != null ? ' (@${item.assignee})' : '';
        final due = item.dueDate != null ? ' - Due: ${DateFormat('MMM d').format(item.dueDate!)}' : '';
        buffer.writeln('$status ${item.content}$assignee$due');
      }
      buffer.writeln();
    }

    // Summary
    final summaries = thread.blocks.where((b) => b.type == SmartBlockType.summary).toList();
    if (summaries.isNotEmpty) {
      buffer.writeln('EXECUTIVE SUMMARY:');
      for (final s in summaries) {
        buffer.writeln(s.content);
      }
      buffer.writeln();
    }

    buffer.writeln('Best regards,');
    buffer.writeln('Convene Meeting Notes');

    final encodedSubject = Uri.encodeComponent(subject);
    final encodedBody = Uri.encodeComponent(buffer.toString());

    return 'mailto:?subject=$encodedSubject&body=$encodedBody';
  }

  /// Copies formatted Markdown export directly to the clipboard.
  static Future<void> copyMarkdownToClipboard(BuildContext context, ContextThread thread, {Group? group}) async {
    final markdown = generateMarkdownExport(thread, group: group);
    await Clipboard.setData(ClipboardData(text: markdown));
    if (context.mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('Meeting minutes copied to clipboard in Markdown format!'),
          duration: Duration(seconds: 3),
        ),
      );
    }
  }

  /// Displays the Export modal bottom sheet with one-click export choices.
  static void showExportBottomSheet(BuildContext context, ContextThread thread, {Group? group}) {
    showModalBottomSheet(
      context: context,
      backgroundColor: context.colors.surface,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(24)),
      ),
      builder: (sheetCtx) => SafeArea(
        child: Padding(
          padding: const EdgeInsets.fromLTRB(20, 16, 20, 24),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Center(
                child: Container(
                  width: 36,
                  height: 4,
                  decoration: BoxDecoration(
                    color: context.colors.textMuted.withValues(alpha: 0.3),
                    borderRadius: BorderRadius.circular(2),
                  ),
                ),
              ),
              const SizedBox(height: 16),
              Text(
                'Export Meeting Summary',
                style: GoogleFonts.plusJakartaSans(
                  fontSize: 18,
                  fontWeight: FontWeight.w700,
                  color: context.colors.textMain,
                ),
              ),
              const SizedBox(height: 6),
              Text(
                'Share formatted meeting outcomes with your team or clients.',
                style: TextStyle(fontSize: 13, color: context.colors.textMuted),
              ),
              const SizedBox(height: 20),

              // Option 1: Copy Markdown
              ListTile(
                contentPadding: EdgeInsets.zero,
                leading: Container(
                  width: 44,
                  height: 44,
                  decoration: BoxDecoration(
                    color: context.colors.primaryLight,
                    borderRadius: BorderRadius.circular(AppRadius.sm),
                  ),
                  child: Icon(Icons.copy_all_rounded, color: context.colors.primary),
                ),
                title: Text(
                  'Copy Markdown',
                  style: GoogleFonts.plusJakartaSans(fontWeight: FontWeight.w700, color: context.colors.textMain),
                ),
                subtitle: Text(
                  'Structured table with decisions, tasks, assignees & due dates',
                  style: TextStyle(fontSize: 12, color: context.colors.textMuted),
                ),
                onTap: () {
                  Navigator.pop(sheetCtx);
                  copyMarkdownToClipboard(context, thread, group: group);
                },
              ),
              const Divider(height: 16),

              // Option 2: Email Digest
              ListTile(
                contentPadding: EdgeInsets.zero,
                leading: Container(
                  width: 44,
                  height: 44,
                  decoration: BoxDecoration(
                    color: const Color(0xFF10B981).withValues(alpha: 0.15),
                    borderRadius: BorderRadius.circular(AppRadius.sm),
                  ),
                  child: const Icon(Icons.email_outlined, color: Color(0xFF10B981)),
                ),
                title: Text(
                  'Send Email Digest',
                  style: GoogleFonts.plusJakartaSans(fontWeight: FontWeight.w700, color: context.colors.textMain),
                ),
                subtitle: Text(
                  'Opens default mail client with formatted summary & action items',
                  style: TextStyle(fontSize: 12, color: context.colors.textMuted),
                ),
                onTap: () async {
                  Navigator.pop(sheetCtx);
                  final mailtoUrl = generateEmailDigestUrl(thread, group: group);
                  final uri = Uri.parse(mailtoUrl);
                  try {
                    await launchUrl(uri, mode: LaunchMode.externalApplication);
                  } catch (e) {
                    if (context.mounted) {
                      copyMarkdownToClipboard(context, thread, group: group);
                    }
                  }
                },
              ),
            ],
          ),
        ),
      ),
    );
  }
}
