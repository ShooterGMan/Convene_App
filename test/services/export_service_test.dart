import 'package:flutter_test/flutter_test.dart';
import 'package:convene/models/context_thread.dart';
import 'package:convene/models/group.dart';
import 'package:convene/models/user.dart';
import 'package:convene/services/export_service.dart';

void main() {
  group('ExportService Tests', () {
    final testThread = ContextThread(
      id: 'thread_101',
      meetingId: 'meet_202',
      meetingTitle: 'Q4 Product Roadmap & Sprint Planning',
      createdAt: DateTime(2026, 8, 27, 10, 30),
      groupId: 'group_55',
      vibe: 'High energy & collaborative',
      participants: const [
        AppUser(id: 'u1', email: 'alex@example.com', name: 'Alex Rivera'),
        AppUser(id: 'u2', email: 'sarah@example.com', name: 'Sarah Chen'),
      ],
      blocks: [
        SmartBlock(
          id: 'b1',
          type: SmartBlockType.summary,
          content: 'Discussed key milestones for Q4 launch and mobile app performance.',
        ),
        SmartBlock(
          id: 'b2',
          type: SmartBlockType.decision,
          content: 'Ship beta build on TestFlight by September 15th.',
        ),
        SmartBlock(
          id: 'b3',
          type: SmartBlockType.actionItem,
          content: 'Finalize design system components',
          assignee: 'Sarah',
          priority: SmartBlockPriority.high,
          dueDate: DateTime(2026, 9, 1),
          isCompleted: false,
        ),
        SmartBlock(
          id: 'b4',
          type: SmartBlockType.keyInsight,
          content: 'WebRTC data channels reduce bandwidth consumption by 40%.',
        ),
      ],
    );

    final testGroup = Group(
      id: 'group_55',
      name: 'Core Mobile Engineering',
      members: const [
        AppUser(id: 'u1', email: 'alex@example.com', name: 'Alex Rivera'),
        AppUser(id: 'u2', email: 'sarah@example.com', name: 'Sarah Chen'),
      ],
      threadIds: const ['thread_101'],
      createdBy: const AppUser(id: 'u1', email: 'alex@example.com', name: 'Alex Rivera'),
      createdAt: DateTime(2026, 1, 1),
    );

    test('generateMarkdownExport formats complete meeting minutes with tables and metadata', () {
      final md = ExportService.generateMarkdownExport(testThread, group: testGroup);

      expect(md, contains('# 📋 Meeting Summary: Q4 Product Roadmap & Sprint Planning'));
      expect(md, contains('**Group / Team:** Core Mobile Engineering'));
      expect(md, contains('**Attendees:** Alex Rivera, Sarah Chen'));
      expect(md, contains('**Meeting Vibe:** High energy & collaborative'));
      expect(md, contains('## 📝 Executive Summary'));
      expect(md, contains('Discussed key milestones for Q4 launch'));
      expect(md, contains('## 🎯 Key Decisions'));
      expect(md, contains('1. **Ship beta build on TestFlight by September 15th.**'));
      expect(md, contains('## ✅ Action Items'));
      expect(md, contains('| Status | Task | Assignee | Priority | Due Date |'));
      expect(md, contains('| ○ Pending | Finalize design system components | @Sarah | HIGH | Sep 1, 2026 |'));
      expect(md, contains('## 💡 Key Insights & Notes'));
      expect(md, contains('WebRTC data channels reduce bandwidth consumption'));
      expect(md, contains('*Generated by Convene AI on'));
    });

    test('generateEmailDigestUrl produces valid mailto URI with encoded summary and tasks', () {
      final mailto = ExportService.generateEmailDigestUrl(testThread, group: testGroup);

      expect(mailto, startsWith('mailto:?subject='));
      expect(mailto, contains('Meeting%20Summary%3A%20Q4%20Product%20Roadmap'));
      expect(mailto, contains('&body='));
      // Verify decoded body contains decisions & action items
      final decoded = Uri.decodeFull(mailto);
      expect(decoded, contains('KEY DECISIONS:'));
      expect(decoded, contains('Ship beta build on TestFlight'));
      expect(decoded, contains('ACTION ITEMS:'));
      expect(decoded, contains('[TODO] Finalize design system components (@Sarah) - Due: Sep 1'));
    });
  });
}
